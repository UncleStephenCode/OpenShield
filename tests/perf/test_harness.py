class KernelBlockAllObservationTests(unittest.TestCase):
    @staticmethod
    def nft_rule(document: dict, chain: str) -> dict:
        for item in document["nftables"]:
            rule = item.get("rule")
            if isinstance(rule, dict) and rule.get("chain") == chain:
                return rule
        raise AssertionError(f"fixture has no rule for {chain}")

    def test_canonical_nft_block_all_is_accepted(self) -> None:
        observation = runner.inspect_nft_block_all(nft_block_all_fixture())
        self.assertTrue(observation["inspected"])
        self.assertTrue(observation["block_all"])
        self.assertIsNone(observation["reason"])

    def test_nft_accept_jump_goto_and_queue_cannot_false_pass(self) -> None:
        for verdict, payload in (
            ("accept", None),
            ("jump", {"target": "permit"}),
            ("goto", {"target": "permit"}),
            ("queue", {"num": 1337}),
        ):
            with self.subTest(verdict=verdict):
                document = json.loads(json.dumps(nft_block_all_fixture()))
                self.nft_rule(document, "input")["expr"][1] = {verdict: payload}
                observation = runner.inspect_nft_block_all(document)
                self.assertTrue(observation["inspected"])
                self.assertFalse(observation["block_all"])

    def test_nft_extra_objects_chains_and_rules_cannot_false_pass(self) -> None:
        mutations = []

        extra_set = json.loads(json.dumps(nft_block_all_fixture()))
        extra_set["nftables"].append(
            {
                "set": {
                    "family": "inet",
                    "table": "openshield",
                    "name": "permit",
                    "type": "ipv4_addr",
                }
            }
        )
        mutations.append(extra_set)

        extra_chain = json.loads(json.dumps(nft_block_all_fixture()))
        extra_chain["nftables"].append(
            {
                "chain": {
                    "family": "inet",
                    "table": "openshield",
                    "name": "permit",
                    "type": "filter",
                    "hook": "output",
                    "prio": -2,
                    "policy": "accept",
                }
            }
        )
        mutations.append(extra_chain)

        extra_rule = json.loads(json.dumps(nft_block_all_fixture()))
        duplicate = json.loads(json.dumps(self.nft_rule(extra_rule, "output")))
        duplicate["handle"] = 99
        extra_rule["nftables"].append({"rule": duplicate})
        mutations.append(extra_rule)

        for index, document in enumerate(mutations):
            with self.subTest(index=index):
                self.assertFalse(runner.inspect_nft_block_all(document)["block_all"])

    def test_nft_tampered_mark_sanitizer_cannot_false_pass(self) -> None:
        document = json.loads(json.dumps(nft_block_all_fixture()))
        sanitizer = self.nft_rule(document, "output_sanitize")["expr"]
        sanitizer[1]["mangle"]["value"]["&"][1] = 0xFFFF_FFFF
        observation = runner.inspect_nft_block_all(document)
        self.assertTrue(observation["inspected"])
        self.assertFalse(observation["block_all"])
        self.assertIn("sanitizer", observation["reason"])

