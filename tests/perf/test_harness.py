    def test_runtime_and_client_config_permissions_are_bounded(self) -> None:
        if os.geteuid() == 0:
            try:
                status = Path("/proc/self/status").read_text(encoding="ascii")
                capability_hex = next(
                    line.split()[1]
                    for line in status.splitlines()
                    if line.startswith("CapEff:")
                )
                effective_capabilities = int(capability_hex, 16)
            except (OSError, StopIteration, ValueError):
                self.skipTest("cannot determine root process capabilities")
            required = (1 << 0) | (1 << 6) | (1 << 7)  # CHOWN, SETGID, SETUID
            if effective_capabilities & required != required:
                self.skipTest(
                    "root process intentionally lacks CHOWN/SETGID/SETUID capabilities"
                )
        target_uid = 65_532 if os.geteuid() == 0 else os.geteuid()
        target_gid = 65_532 if os.geteuid() == 0 else os.getegid()
        with tempfile.TemporaryDirectory() as directory:
            Path(directory).chmod(0o711)
            state = Path(directory) / "runtime"
            subprocess.run(
                [
                    sys.executable,
                    "-c",
                    runner.CONTAINER_WORKLOAD_PREPARER,
                    str(state),
                    str(target_uid),
                    str(target_gid),
                ],
                check=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
            config_directory = state / "config"
            homes = state / "users"
            home = homes / str(target_uid)
            identity_options = {}
            if os.geteuid() == 0:
                identity_options = {
                    "user": target_uid,
                    "group": target_gid,
                    "extra_groups": [],
                }
            subprocess.run(
                [
                    sys.executable,
                    "-c",
                    runner.CONTAINER_WORKLOAD_HOME_PREPARER,
                    str(home),
                ],
                check=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                **identity_options,
            )
            self.assertEqual(stat.S_IMODE(state.stat().st_mode), 0o711)
            self.assertEqual(stat.S_IMODE(config_directory.stat().st_mode), 0o711)
            self.assertEqual(stat.S_IMODE(homes.stat().st_mode), 0o1733)
            self.assertEqual(stat.S_IMODE(home.stat().st_mode), 0o700)
            self.assertEqual(home.stat().st_uid, target_uid)
            self.assertEqual(home.stat().st_gid, target_gid)

            config = config_directory / "phase.json"
            payload = b'{"port":12345}'
            command = [
                sys.executable,
                "-c",
                runner.CONTAINER_CONFIG_INSTALLER,
                str(config),
                str(target_uid),
                str(target_gid),
                str(config_directory),
            ]
            subprocess.run(
                command,
                input=payload,
                check=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
            metadata = config.stat()
            self.assertEqual(config.read_bytes(), payload)
            self.assertEqual(metadata.st_uid, os.geteuid())
            self.assertEqual(metadata.st_gid, os.getegid())
            self.assertEqual(stat.S_IMODE(metadata.st_mode), 0o644)
            self.assertEqual(metadata.st_nlink, 1)

            reader = subprocess.run(
                [
                    sys.executable,
                    "-c",
                    "import pathlib,sys;sys.stdout.buffer.write(pathlib.Path(sys.argv[1]).read_bytes())",
                    str(config),
                ],
                check=False,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                **identity_options,
            )
            self.assertEqual(reader.returncode, 0, reader.stderr.decode(errors="replace"))
            self.assertEqual(reader.stdout, payload)
            if target_uid != os.geteuid():
                writer = subprocess.run(
                    [
                        sys.executable,
                        "-c",
                        "import pathlib,sys;pathlib.Path(sys.argv[1]).write_bytes(b'changed')",
                        str(config),
                    ],
                    check=False,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    **identity_options,
                )
                self.assertNotEqual(writer.returncode, 0)
                self.assertEqual(config.read_bytes(), payload)

            outside = Path(directory) / "outside.json"
            rejected = subprocess.run(
                [
                    sys.executable,
                    "-c",
                    runner.CONTAINER_CONFIG_INSTALLER,
                    str(outside),
                    str(target_uid),
                    str(target_gid),
                    str(config_directory),
                ],
                input=payload,
                check=False,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
            self.assertNotEqual(rejected.returncode, 0)
            self.assertFalse(outside.exists())
            if target_uid != os.geteuid():
                # A UID-0 test process can intentionally lack DAC_OVERRIDE and
                # FOWNER in the release quality container. Let the fixed
                # workload identity remove its own 0700 directory so
                # TemporaryDirectory cleanup does not require either cap.
                subprocess.run(
                    [
                        sys.executable,
                        "-c",
                        "import os,sys;os.rmdir(sys.argv[1])",
                        str(home),
                    ],
                    check=True,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    **identity_options,
                )


